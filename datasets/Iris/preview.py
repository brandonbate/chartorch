def _load(split="train"):
    if split not in _datasets:
        if split == "test":
            x = torch.tensor(test0 + test1 + test2, dtype=torch.float32)
            y = torch.tensor([0] * len(test0) + [1] * len(test1) + [2] * len(test2), dtype=torch.long)
        else:
            x = torch.tensor(train0 + train1 + train2, dtype=torch.float32)
            y = torch.tensor([0] * len(train0) + [1] * len(train1) + [2] * len(train2), dtype=torch.long)
        _datasets[split] = TensorDataset(x, y)
    return _datasets[split]


def _fmt(t):
    if hasattr(t, "detach"):
        t = t.detach().cpu()
    if hasattr(t, "numel") and t.numel() == 1:
        return str(t.item())
    if hasattr(t, "tolist"):
        vals = t.tolist()
        if isinstance(vals, list):
            return str([round(v, 1) if isinstance(v, float) else v for v in vals])
        return str(vals)
    return str(t)


def preview(index=0, split="train"):
    if split not in ("train", "test"):
        split = "train"
    dataset = _load(split)
    size = len(dataset)
    index = 0 if size == 0 else max(0, min(int(index), size - 1))
    inp, label = dataset[index]
    input_shape = list(inp.shape)
    label_shape = list(label.shape) if hasattr(label, "shape") else []
    return {
        "kind": "text",
        "text": _fmt(inp),
        "label": _fmt(label),
        "input_shape": input_shape,
        "label_shape": label_shape,
        "index": index,
        "size": size,
    }


def chart(split="train"):
    if split not in ("train", "test"):
        split = "train"
    dataset = _load(split)
    charts = []
    for xi, yi in CHART_PAIRS:
        points = []
        for i in range(len(dataset)):
            inp, label = dataset[i]
            xy = inp.reshape(-1)
            cls = int(label.reshape(-1)[0].item())
            points.append({
                "x": float(xy[xi].item()),
                "y": float(xy[yi].item()),
                "color": CLASS_COLORS.get(cls, "#333333"),
            })
        charts.append({
            "id": f"{xi}-{yi}",
            "label": f"{FEATURE_NAMES[xi]} vs {FEATURE_NAMES[yi]}",
            "xi": xi,
            "yi": yi,
            "x_label": FEATURE_NAMES[xi],
            "y_label": FEATURE_NAMES[yi],
            "points": points,
        })
    return charts
